CREATE TABLE T_User (
    Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    DisplayName VARCHAR(255) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    EmailKey VARCHAR(255) COLLATE utf8mb4_bin NOT NULL,
    PasswordHash VARCHAR(255) NULL,
    Phone VARCHAR(255) NULL,
    ProfileImage VARCHAR(255) NULL,
    IsAdmin BOOLEAN NOT NULL DEFAULT FALSE CHECK (IsAdmin IN (0, 1)),
    IsActive BOOLEAN NOT NULL DEFAULT TRUE CHECK (IsActive IN (0, 1)),
    EmailVerified BOOLEAN NOT NULL DEFAULT FALSE CHECK (EmailVerified IN (0, 1)),
    CreatedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AdjustedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    UNIQUE KEY uq_user_email (EmailKey),
    UNIQUE KEY uq_user_admin_flag (Id, IsAdmin)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE T_Admin (
    Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId BIGINT UNSIGNED NOT NULL UNIQUE,
    AdminFlag BOOLEAN NOT NULL DEFAULT TRUE CHECK (AdminFlag = 1),
    GrantedDate DATETIME(6) NULL,
    GrantedByUserId BIGINT UNSIGNED NULL,
    CreatedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AdjustedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_admin_user FOREIGN KEY (UserId, AdminFlag) REFERENCES T_User (Id, IsAdmin)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_admin_granter FOREIGN KEY (GrantedByUserId) REFERENCES T_User (Id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

