    PaymentStatus VARCHAR(24) NOT NULL,
    OrderStatus VARCHAR(24) NOT NULL,
    ConfirmationRequested BOOLEAN NOT NULL DEFAULT FALSE CHECK (ConfirmationRequested IN (0, 1)),
    PromotecodeId BIGINT UNSIGNED NULL,
    PromotionCodeSnapshot VARCHAR(255) NULL,
    ShippingAddressSnapshot VARCHAR(255) NULL,
    ShippingRecipientSnapshot VARCHAR(255) NULL,
    ShippingPhoneSnapshot VARCHAR(255) NULL,
    CreatedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AdjustedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    KEY ix_order_user_date (UserId, OrderedOn, Id),
    KEY ix_order_reporting_date (OrderedOn),
    KEY ix_order_user_promotion (UserId, PromotecodeId),
    CONSTRAINT fk_order_user FOREIGN KEY (UserId) REFERENCES T_User (Id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_promotion FOREIGN KEY (PromotecodeId) REFERENCES T_Promotecode (Id) ON DELETE SET NULL
