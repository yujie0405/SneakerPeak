CREATE TABLE T_Product (
    Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    BrandId BIGINT UNSIGNED NOT NULL,
    SubCategoryId BIGINT UNSIGNED NOT NULL,
    CategoryId BIGINT UNSIGNED NOT NULL,
    Name VARCHAR(255) NOT NULL,
    Price DECIMAL(13,2) NOT NULL CHECK (Price >= 0),
    Colour VARCHAR(255) NULL,
    Details TEXT NOT NULL,
    Image1Path VARCHAR(255) NULL,
    Image2Path VARCHAR(255) NULL,
    Image3Path VARCHAR(255) NULL,
    ProductStatusId TINYINT UNSIGNED NOT NULL,
    CreatedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AdjustedDate DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    KEY ix_product_catalog (ProductStatusId, Name, Id),
    UNIQUE KEY uq_product_name (Name),
    CONSTRAINT fk_product_brand FOREIGN KEY (BrandId) REFERENCES E_Brand (Id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_subcategory FOREIGN KEY (SubCategoryId) REFERENCES E_SubCategory (Id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_category FOREIGN KEY (CategoryId) REFERENCES E_Category (Id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_status FOREIGN KEY (ProductStatusId) REFERENCES E_ProductStatus (Id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

